function applyTranslations() {
    const lang = localStorage.getItem('lang') || 'en';
    const dict = TRANSLATIONS[lang];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (dict[key]) {
            // Handle elements with children carefully if needed, but mostly textContent
            if (el.children.length === 0) {
                el.textContent = dict[key];
            } else {
                // If it has children (like icons), we might need a more specific approach
                // or just ensure the translatable text is in its own span.
                // For now, let's assume direct text nodes for simple cases.
                // If an element has children, we replace only the text node part.
                const textNode = Array.from(el.childNodes).find(node => node.nodeType === Node.TEXT_NODE);
                if (textNode) {
                    textNode.textContent = dict[key];
                } else {
                    // Fallback for elements that might be intended to be replaced entirely
                    // el.textContent = dict[key];
                }
            }
        }
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
        const attrPairs = el.dataset.i18nAttr.split(',');
        attrPairs.forEach(pair => {
            const [attr, key] = pair.split(':').map(s => s.trim());
            if (dict[key]) el.setAttribute(attr, dict[key]);
        });
    });

    // Sync toggle button state
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
        const isActive = btn.dataset.lang === lang;
        btn.classList.toggle('text-[#f7941d]', isActive);
        btn.classList.toggle('text-neutral-400', !isActive);
        btn.classList.toggle('font-bold', isActive);
    });

    document.documentElement.lang = lang;
}

function setLanguage(lang) {
    localStorage.setItem('lang', lang);
    applyTranslations();
}

document.addEventListener('DOMContentLoaded', applyTranslations);
